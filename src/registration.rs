use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use anyhow::{Result, bail};

use crate::compose::transform::Env;
use crate::config::Registration;
use crate::state::BayState;

/// Lines a bay needs in a shared service, one set per bay service defining the matched variable.
pub fn lines(
    registration: &Registration,
    bay: &str,
    services: &BTreeSet<String>,
    envs: &BTreeMap<String, Env>,
) -> Vec<String> {
    if services.contains(&registration.service) {
        return Vec::new();
    }
    let mut lines = Vec::new();
    for (service, env) in envs {
        let Some(host) = env
            .get(&registration.match_env)
            .and_then(|url| host_of(url))
        else {
            continue;
        };
        for template in &registration.lines {
            lines.push(
                template
                    .replace("{BAY}", &constant(bay))
                    .replace("{SERVICE}", &constant(service))
                    .replace("{host}", host),
            );
        }
    }
    lines
}

/// First line of a registration file, telling it apart from a file bayplan must not overwrite.
const HEADER: &str = "# Generated by bayplan: lines the bays need in this service";

/// Writes the lines of every bay to the file of the registration. Returns whether the file changed.
pub fn write(root: &Path, registration: &Registration, states: &[BayState]) -> Result<bool> {
    let path = root.join(&registration.env_file);
    let key = registration.env_file.to_string_lossy();
    if let Ok(existing) = std::fs::read_to_string(&path)
        && !existing.starts_with(HEADER)
    {
        bail!(
            "{} exists and was not written by bayplan: point the registration at a file of its own",
            path.display()
        );
    }
    let mut content = format!("{HEADER}\n");
    for state in states {
        for line in state.registrations.get(key.as_ref()).into_iter().flatten() {
            content.push_str(line);
            content.push('\n');
        }
    }
    if std::fs::read_to_string(&path).ok().as_deref() == Some(content.as_str()) {
        return Ok(false);
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&path, content)?;
    Ok(true)
}

fn constant(name: &str) -> String {
    name.to_uppercase().replace(['-', '.'], "_")
}

fn host_of(url: &str) -> Option<&str> {
    let rest = url.split_once("://").map_or(url, |(_, rest)| rest);
    rest.split(['/', ':', '?'])
        .next()
        .filter(|host| !host.is_empty())
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use super::*;

    fn registration() -> Registration {
        Registration {
            service: "auth".to_owned(),
            env_file: PathBuf::from(".bayplan/auth.env"),
            match_env: "AUTH_URL".to_owned(),
            lines: vec!["REDIRECT_URI_BAY_{BAY}_{SERVICE}=https://{host}/callback".to_owned()],
        }
    }

    #[test]
    fn registers_each_service_defining_the_variable() {
        let services: BTreeSet<String> = ["dashboard-app".to_owned(), "api".to_owned()].into();
        let envs = BTreeMap::from([
            (
                "dashboard-app".to_owned(),
                Env::from([(
                    "AUTH_URL".to_owned(),
                    "https://dashboard-demo.app.localhost".to_owned(),
                )]),
            ),
            ("api".to_owned(), Env::new()),
        ]);
        assert_eq!(
            lines(&registration(), "my-bay", &services, &envs),
            ["REDIRECT_URI_BAY_MY_BAY_DASHBOARD_APP=https://dashboard-demo.app.localhost/callback"]
        );
    }

    #[test]
    fn skips_when_the_bay_runs_the_service_itself() {
        let services: BTreeSet<String> = ["auth".to_owned()].into();
        let envs = BTreeMap::from([(
            "auth".to_owned(),
            Env::from([(
                "AUTH_URL".to_owned(),
                "https://auth-demo.app.localhost".to_owned(),
            )]),
        )]);
        assert_eq!(
            lines(&registration(), "demo", &services, &envs),
            Vec::<String>::new()
        );
    }
}
